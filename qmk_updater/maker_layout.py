"""Small, packaging-only maker window. Protocol overrides live in a dialog."""
from . import __version__
from .qt import *
from .ui import ROOT, label, button, form_field, show_licenses
from .layouts import Panel, compact_field, apply_compact_theme
from .appearance import BACKGROUNDS, CustomerPreview
from .runtimes import TARGETS, host_target


def build_maker_window(window):
    window.setWindowTitle("QMK 升级包制作  v" + __version__)
    window.setWindowIcon(QIcon(str(ROOT / "icon.png")))
    window.resize(960, 610)
    window.setMinimumSize(920, 580)
    window.firmware = None
    window.firmware_path = None
    window.accent = "#83ADF2"
    window.inputs = {}
    window.setAcceptDrops(True)
    outer = QWidget()
    window.setCentralWidget(outer)
    box = QVBoxLayout(outer)
    box.setContentsMargins(16, 14, 16, 14)
    box.setSpacing(9)
    header = QHBoxLayout()
    logo = QLabel()
    logo.setPixmap(QPixmap(str(ROOT / "icon.png")).scaled(28, 28, Qt.KeepAspectRatio, Qt.SmoothTransformation))
    header.addWidget(logo)
    header.addSpacing(5)
    title = label("固件升级包制作", "title")
    title.setStyleSheet("font-size: 22px; font-weight: 700;")
    header.addWidget(title)
    header.addStretch()
    box.addLayout(header)
    columns = QHBoxLayout()
    columns.setSpacing(14)
    main = QWidget()
    left = QVBoxLayout(main)
    left.setContentsMargins(0, 0, 0, 0)
    left.setSpacing(9)
    columns.addWidget(main, 1)
    window.customer_preview = CustomerPreview()
    columns.addWidget(window.customer_preview)
    box.addLayout(columns, 1)
    box = left

    firmware = Panel("固件")
    firmware.box.setContentsMargins(12, 9, 12, 9)
    firmware.box.setSpacing(6)
    row = QHBoxLayout()
    window.file_label = compact_field("", "选择 HEX / BIN，或拖入固件")
    window.file_label.setReadOnly(True)
    choose = button("选择固件…")
    choose.setMinimumHeight(30)
    choose.clicked.connect(window.select_firmware)
    row.addWidget(window.file_label, 1)
    row.addWidget(choose)
    firmware.box.addLayout(row)
    grid = QGridLayout()
    grid.setHorizontalSpacing(10)
    window.inputs["product"] = compact_field("", "设备名称")
    window.inputs["version"] = compact_field("", "例如 1.0.9")
    window.output_name = compact_field("", "默认使用 HEX / BIN 文件名，可修改")
    form_field(grid, 0, 0, "设备名称", window.inputs["product"])
    form_field(grid, 0, 1, "固件版本", window.inputs["version"])
    form_field(grid, 0, 2, "升级包文件名", window.output_name)
    grid.setColumnStretch(0, 2)
    grid.setColumnStretch(1, 1)
    grid.setColumnStretch(2, 2)
    firmware.box.addLayout(grid)
    window.file_meta = label("支持 .hex / .bin", "tiny")
    firmware.box.addWidget(window.file_meta)
    box.addWidget(firmware)

    app = Panel("键盘参数 · APP")
    app.box.setContentsMargins(12, 9, 12, 9)
    app.box.setSpacing(6)
    grid = QGridLayout()
    grid.setHorizontalSpacing(10)
    for col, (key, title, value) in enumerate([
            ("app_vid", "VID", "342D"), ("app_pid", "PID", "E594"),
            ("usage_page", "Usage Page", "FF60"), ("usage_id", "Usage ID", "0061")]):
        window.inputs[key] = compact_field(value, "", True)
        window.inputs[key].setMaxLength(6)
        form_field(grid, 0, col, title, window.inputs[key])
    app.box.addLayout(grid)
    box.addWidget(app)

    publish = Panel("发布设置")
    publish.box.setContentsMargins(12, 9, 12, 9)
    publish.box.setSpacing(9)
    row = QHBoxLayout()
    row.addWidget(label("客户系统", "fieldLabel"))
    window.platform_combo = QComboBox()
    for target, (title, extension) in TARGETS.items():
        window.platform_combo.addItem(title, target)
    window.platform_combo.setCurrentIndex(window.platform_combo.findData(host_target()))
    row.addWidget(window.platform_combo, 1)
    import_button = button("导入模板")
    import_button.setMinimumHeight(30)
    import_button.clicked.connect(window.import_runtime)
    row.addWidget(import_button)
    publish.box.addLayout(row)
    window.platform_status = label("", "tiny")
    publish.box.addWidget(window.platform_status)
    row = QHBoxLayout()
    row.addWidget(label("升级页背景", "fieldLabel"))
    window.background_combo = QComboBox()
    for title, color in BACKGROUNDS:
        window.background_combo.addItem(title, color)
    window.background_combo.setMinimumWidth(125)
    row.addWidget(window.background_combo)
    row.addStretch()
    publish.box.addLayout(row)
    row = QHBoxLayout()
    row.setSpacing(18)
    window.single_mode = QRadioButton("单次烧录")
    window.continuous_mode = QRadioButton("连续烧录")
    for choice in (window.single_mode, window.continuous_mode):
        choice.setObjectName("modeChoice")
        choice.setMinimumSize(104, 30)
        choice.setCursor(Qt.PointingHandCursor)
    window.mode_group = QButtonGroup(window)
    window.mode_group.addButton(window.single_mode)
    window.mode_group.addButton(window.continuous_mode)
    window.single_mode.setChecked(True)
    window.auto_start = QCheckBox("打开后自动开始")
    window.auto_start.setChecked(True)
    window.auto_start.setToolTip("勾选：打开升级包后识别键盘即开始；取消：客户点击开始按钮后才升级。")
    row.addWidget(window.single_mode)
    row.addWidget(window.continuous_mode)
    row.addWidget(window.auto_start)
    row.addStretch()
    publish.box.addLayout(row)
    window.mode_hint = label("单次：成功退出 DFU 后，倒计时 5 秒关闭。", "tiny")
    publish.box.addWidget(window.mode_hint)
    box.addWidget(publish)
    box.addStretch()

    footer = QHBoxLayout()
    window.status = label("请选择固件", "muted", True)
    footer.addWidget(window.status, 1)
    advanced = button("高级参数")
    advanced.setObjectName("link")
    advanced.clicked.connect(lambda: window.advanced_dialog.open())
    footer.addWidget(advanced)
    footer.addSpacing(14)
    window.generate = button("生成升级包", True)
    window.generate.setMinimumWidth(166)
    window.generate.setEnabled(False)
    window.generate.clicked.connect(window.generate_package)
    footer.addWidget(window.generate)
    box.addLayout(footer)

    window.advanced_dialog = QDialog(window)
    window.advanced_dialog.setWindowTitle("高级参数")
    window.advanced_dialog.resize(550, 390)
    advanced_box = QVBoxLayout(window.advanced_dialog)
    advanced_box.setContentsMargins(20, 18, 20, 18)
    advanced_box.setSpacing(12)
    grid = QGridLayout()
    grid.setSpacing(10)
    for index, (key, title, value) in enumerate([
            ("boot_vid", "Boot VID", "342D"), ("boot_pid", "Boot PID", "DFA0"),
            ("report_size", "APP 报告字节（十进制）", "32"), ("report_id", "APP Report ID（十六进制）", "00")]):
        window.inputs[key] = compact_field(value, "", True)
        form_field(grid, index // 2, index % 2, title, window.inputs[key])
    window.base = compact_field("08000000", "", True)
    form_field(grid, 2, 0, "APP / BIN 地址  0x", window.base)
    window.apply_base = button("重新解析 BIN")
    window.apply_base.clicked.connect(window.reload_bin)
    grid.addWidget(window.apply_base, 2, 1, Qt.AlignBottom)
    window.usb_combo = QComboBox()
    window.usb_combo.addItem("等待选择固件")
    window.usb_combo.currentIndexChanged.connect(window.choose_usb)
    window.hid_combo = QComboBox()
    window.hid_combo.addItem("等待识别 Raw HID")
    window.hid_combo.currentIndexChanged.connect(window.choose_hid)
    form_field(grid, 3, 0, "固件内 USB 标识", window.usb_combo)
    form_field(grid, 3, 1, "固件内 Raw HID", window.hid_combo)
    window.usb_version = compact_field()
    window.usb_version.setReadOnly(True)
    window.firmware_size = compact_field()
    window.firmware_size.setReadOnly(True)
    form_field(grid, 4, 0, "USB 版本", window.usb_version)
    form_field(grid, 4, 1, "固件大小", window.firmware_size)
    advanced_box.addLayout(grid)
    window.boot_recovery = QCheckBox("允许从 Boot 恢复")
    window.boot_recovery.setToolTip("Boot 不包含键盘型号标识，仅为确定型号的恢复包开启。")
    advanced_box.addWidget(window.boot_recovery)
    row = QHBoxLayout()
    licenses = button("软件许可")
    licenses.setObjectName("link")
    licenses.clicked.connect(lambda: show_licenses(window.advanced_dialog))
    row.addWidget(licenses)
    row.addStretch()
    done = button("完成")
    done.clicked.connect(window.advanced_dialog.accept)
    row.addWidget(done)
    advanced_box.addLayout(row)
    window.single_mode.toggled.connect(window.refresh_preview)
    window.continuous_mode.toggled.connect(window.refresh_preview)
    window.auto_start.toggled.connect(window.refresh_preview)
    window.platform_combo.currentIndexChanged.connect(window.refresh_preview)
    window.background_combo.currentIndexChanged.connect(window.refresh_preview)
    window.inputs["product"].textChanged.connect(window.refresh_preview)
    window.inputs["version"].textChanged.connect(window.refresh_preview)
    window.output_name.textChanged.connect(window.refresh_preview)
    for key in ("app_vid", "app_pid", "usage_page", "usage_id", "boot_vid", "boot_pid"):
        window.inputs[key].textChanged.connect(window.refresh_preview)
    window.base.textChanged.connect(window.refresh_preview)
    apply_compact_theme(window, window.accent)
    window.refresh_preview()
